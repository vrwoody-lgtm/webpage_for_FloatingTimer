const languageButtons = document.querySelectorAll("[data-language]");
const translatable = document.querySelectorAll("[data-i18n]");

function setLanguage(language) {
  const copy = translations[language] || translations.zh;
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.title = copy.title;
  document.querySelector('meta[name="description"]')?.setAttribute("content", copy.description);
  translatable.forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (typeof value !== "string") return;
    if (element.dataset.i18nMode === "html") element.innerHTML = value;
    else element.textContent = value;
  });
  languageButtons.forEach((button) => {
    const active = button.dataset.language === language;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  try { localStorage.setItem("floatingtimer-language", language); } catch (_) { }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

let preferredLanguage = "zh";
try {
  preferredLanguage = localStorage.getItem("floatingtimer-language") || (navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en");
} catch (_) { }
setLanguage(preferredLanguage);
